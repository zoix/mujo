-- mujo: Hyprland entry point (Hyprland 0.55 or newer reads this file).
--
-- Each require() runs in its own scope, so an error in one module is reported
-- and the others still load. Modules, in load order:
--   compat      app compatibility fixes ported from the old hyprland.conf
--   look        gaps, borders, rounding, colours (from mujo_tokens)
--   animations  curves and speeds (from mujo_tokens; off with reduce_motion)
--   input       keyboard and pointer defaults
--   binds       every keybinding, each with a description for `mujo keys`
--   rules       window rules (floating mujo TUIs)
--   autostart   session daemons
--   host        this machine: monitors, keyboard layout, lid switch.
--               Written once by install.sh and never overwritten; edit freely.
--   battery     what is saved while on battery (`mujo power battery`)
--
-- mujo_tokens.lua is generated by `mujo theme build`. Do not edit it.
--
-- The modules above are links into the mujo checkout, and Hyprland resolves
-- relative requires from the real location of this file. host.lua and
-- mujo_tokens.lua exist only in ~/.config/hypr, so they are required by
-- absolute path.

local cfg = (os.getenv("XDG_CONFIG_HOME") or (os.getenv("HOME") .. "/.config")) .. "/hypr/"

require("compat")
require("look")
require("animations")
require("input")
require("binds")
require("rules")
require("autostart")
require(cfg .. "host")
require("battery")
